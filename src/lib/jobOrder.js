function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, (character) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  })[character]);
}

export function isJobOrderVerified(request) {
  return request?.status === 'closed'
    && request?.techState === 'completed'
    && Boolean(request?.verifiedAt);
}

export function printJobOrder(request, action = 'print') {
  if (!request?.id || !request?.title) throw new Error('A valid service request is required.');
  if (!isJobOrderVerified(request)) {
    throw new Error('The job order is available after the request has been verified and closed.');
  }
  const printWindow = window.open('', '_blank');
  if (!printWindow) throw new Error('The print window was blocked. Allow pop-ups and try again.');
  printWindow.opener = null;

  const date = request.date || request.requestDate || new Date().toLocaleDateString();
  const serviceType = request.cat || request.category || 'Facilities service';
  const requester = request.requester || 'Not provided';
  const office = request.dept || request.department || 'Not provided';
  const description = request.details || request.description || request.title;
  const code = request.trackingCode || request.tracking_code || request.id;
  const completedAt = request.completedAt ? new Date(request.completedAt).toLocaleString() : 'Recorded';
  const verifiedAt = request.verifiedAt ? new Date(request.verifiedAt).toLocaleString() : 'Verified';
  const verificationNote = request.adminResponse || 'Verified and closed by administration.';
  const title = action === 'pdf' ? 'Save UNIFIX Job Order as PDF' : 'UNIFIX Job Order';

  printWindow.document.write(`<!doctype html>
    <html lang="en">
    <head>
      <meta charset="utf-8">
      <meta name="viewport" content="width=device-width,initial-scale=1">
      <title>${escapeHtml(title)} - ${escapeHtml(code)}</title>
      <style>
        *{box-sizing:border-box}body{font:12px Arial,sans-serif;color:#18231d;margin:16mm}
        header{text-align:center;border-bottom:2px solid #0f6b3d;padding-bottom:12px;margin-bottom:18px}
        header h1{font-size:19px;color:#0f6b3d;margin:0 0 4px}header p{margin:0;color:#52635a}
        h2{font-size:13px;text-transform:uppercase;letter-spacing:.5px;color:#0a4f2d;margin:20px 0 8px}
        table{border-collapse:collapse;width:100%}th,td{border:1px solid #aebbb2;padding:9px;vertical-align:top;text-align:left}
        th{width:24%;background:#edf4ef}.description{min-height:90px;white-space:pre-wrap}
        .signatures{display:grid;grid-template-columns:repeat(3,1fr);gap:20px;margin-top:42px}
        .signature{padding-top:36px;border-bottom:1px solid #333;text-align:center}.signature span{display:block;margin-top:6px}
        .completion{height:95px}.small{font-size:10px;color:#52635a;margin-top:20px}
        @page{size:A4 portrait;margin:14mm}@media print{body{margin:0}}
      </style>
    </head>
    <body>
      <header><h1>NUEVA VIZCAYA STATE UNIVERSITY</h1><p>UNIFIX Campus Maintenance · Service Job Order</p></header>
      <table>
        <tr><th>Control number</th><td>${escapeHtml(code)}</td><th>Date</th><td>${escapeHtml(date)}</td></tr>
        <tr><th>Requester</th><td>${escapeHtml(requester)}</td><th>Office / Department</th><td>${escapeHtml(office)}</td></tr>
        <tr><th>Service type</th><td>${escapeHtml(serviceType)}</td><th>Request title</th><td>${escapeHtml(request.title)}</td></tr>
      </table>
      <h2>Work requested</h2><table><tr><td class="description">${escapeHtml(description)}</td></tr></table>
      <div class="signatures">
        <div><div class="signature"></div><span>Requester</span></div>
        <div><div class="signature"></div><span>Department Head</span></div>
        <div><div class="signature"></div><span>Maintenance Head</span></div>
      </div>
      <h2>Completion and verification</h2>
      <table><tr><th>Verification status</th><td>Verified and closed</td></tr>
        <tr><th>Verified on</th><td>${escapeHtml(verifiedAt)}</td></tr>
        <tr><th>Date completed</th><td>${escapeHtml(completedAt)}</td></tr>
        <tr><th>Administrator confirmation</th><td>${escapeHtml(verificationNote)}</td></tr>
        <tr><th>Work performed / materials used</th><td class="completion"></td></tr>
        <tr><th>Accepted by / signature</th><td class="completion"></td></tr>
      </table>
      <p class="small">Generated by UNIFIX. This job order is for processing and acceptance of the facilities service request.</p>
      <script>window.addEventListener('load',()=>window.print())<\/script>
    </body>
    </html>`);
  printWindow.document.close();
}
